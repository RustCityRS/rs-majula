/// The frame size the client reads `opcode` with: a byte count, `-1` for a
/// var-byte frame, `-2` for var-short. `None` for an opcode it has no prot for.
pub fn frame_size(opcode: u16) -> Option<i8> {
    SERVER_PROTS
        .iter()
        .find(|(_, id, _)| *id as u16 == opcode)
        .map(|(_, _, size)| *size)
}

/// The client's name for `opcode`.
pub fn name(opcode: u16) -> Option<&'static str> {
    SERVER_PROTS
        .iter()
        .find(|(_, id, _)| *id as u16 == opcode)
        .map(|(name, _, _)| *name)
}
