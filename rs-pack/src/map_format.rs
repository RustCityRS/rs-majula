//! Map archive format: terrain (`m_X_Z`) and landscape (`l_X_Z`) binary ↔ text.
//!
//! Archive 5 (MAPS) groups use two formats documented in
//! `docs/cache/rev-647-map-format.md`. Terrain stores per-tile heights,
//! overlays, flags, and underlays. Landscape stores delta-coded loc
//! placements. Landscape groups are XTEA-encrypted.

use std::collections::HashMap;
use std::path::Path;

use anyhow::{Context, Result};
use rs_dat2::xtea::java_string_hash;
use serde::{Deserialize, Serialize};

pub const MAP_ARCHIVE: u8 = 5;
const TILES_PER_MAP: usize = 4 * 64 * 64;

// ── Manifest ───────────────────────────────────────────────────────────────

#[derive(Debug, Serialize, Deserialize)]
pub struct MapManifest {
    pub archive_id: u8,
    pub groups: Vec<MapGroupEntry>,
}

#[derive(Debug, Serialize, Deserialize)]
pub struct MapGroupEntry {
    pub group_id: u32,
    pub name: String,
    pub file_name: String,
    pub compression: u8,
    pub version: u16,
    pub compressed_len: u32,
    pub decompressed_len: u32,
    pub crc: u32,
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub encrypted: bool,
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub keyed: bool,
}

// ── Name hash lookup ───────────────────────────────────────────────────────

pub fn build_name_lookup() -> HashMap<i32, String> {
    let mut lookup = HashMap::new();
    // Rev 647 uses five prefixes: m (terrain), l (landscape/locs),
    // n (NPC spawns), um (underwater terrain), ul (underwater locs).
    for prefix in ["m", "l", "n", "um", "ul"] {
        for mx in 0..=255u32 {
            for mz in 0..=255u32 {
                let name = format!("{}{}_{}", prefix, mx, mz);
                lookup.entry(java_string_hash(&name)).or_insert(name);
            }
        }
    }
    lookup
}

pub fn is_landscape(name: &str) -> bool {
    name.starts_with("l") || name.starts_with("ul")
}

pub fn is_npc_spawns(name: &str) -> bool {
    name.starts_with("n") && !name.starts_with("nl")
}

/// Global ground-item spawn files are named `o<mx>_<mz>` (no other rev-647
/// map prefix begins with `o`).
pub fn is_obj_spawns(name: &str) -> bool {
    name.starts_with('o')
}

pub fn terrain_levels(name: &str) -> usize {
    if name.starts_with("um") { 1 } else { 4 }
}

// ── Square sources ─────────────────────────────────────────────────────────

/// Where `<name>.jm2` squares come from, lowest priority first:
///
/// 1. `maps/_unpack` — the cache's own, regenerated by `cargo unpack`, never
///    edited by hand;
/// 2. `maps/spawns` — npc (`n`) and ground-obj (`o`) spawns, server data the
///    cache does not carry;
/// 3. `maps/donor` — squares rebuilt from donor caches, because the 786
///    copies are encrypted under keys nobody has.
///
/// A square in a later directory replaces the same square in an earlier one.
pub fn source_dirs(content_dir: &Path) -> [std::path::PathBuf; 3] {
    let maps = content_dir.join("maps");
    [
        maps.join("_unpack"),
        maps.join("spawns"),
        maps.join("donor"),
    ]
}

/// `<name>.jm2` from the highest-priority directory that has it.
pub fn find_square(dirs: &[std::path::PathBuf], name: &str) -> Option<std::path::PathBuf> {
    dirs.iter()
        .rev()
        .map(|dir| dir.join(format!("{name}.jm2")))
        .find(|path| path.is_file())
}

/// Every `.jm2` square across `dirs`, by stem, later directories winning.
pub fn squares(
    dirs: &[std::path::PathBuf],
) -> std::collections::BTreeMap<String, std::path::PathBuf> {
    let mut out = std::collections::BTreeMap::new();
    for dir in dirs {
        let Ok(entries) = std::fs::read_dir(dir) else {
            continue;
        };
        for path in entries.flatten().map(|e| e.path()) {
            if path.extension().and_then(|e| e.to_str()) != Some("jm2") {
                continue;
            }
            if let Some(stem) = path.file_stem().and_then(|s| s.to_str()) {
                out.insert(stem.to_string(), path);
            }
        }
    }
    out
}

// ── XTEA key loading ───────────────────────────────────────────────────────

pub fn load_xtea_keys(keys_path: &Path) -> Result<HashMap<i32, [i32; 4]>> {
    #[derive(Deserialize)]
    struct KeyEntry {
        archive: u8,
        #[allow(dead_code)]
        group: u32,
        key: [i32; 4],
        name_hash: i32,
    }

    let data = std::fs::read_to_string(keys_path)
        .with_context(|| format!("reading {}", keys_path.display()))?;
    let entries: Vec<KeyEntry> = serde_json::from_str(&data)?;
    let mut map = HashMap::new();
    for entry in entries {
        if entry.archive == MAP_ARCHIVE {
            map.insert(entry.name_hash, entry.key);
        }
    }
    Ok(map)
}

