impl TerrainTile {
    fn has_any(&self) -> bool {
        self.height.is_some()
            || self.overlay_id.is_some()
            || self.flags.is_some()
            || self.underlay_id.is_some()
    }
}

// ── Landscape types ────────────────────────────────────────────────────────

#[derive(Debug, Clone)]
pub struct LocEntry {
    pub loc_id: u32,
    pub level: u8,
    pub x: u8,
    pub z: u8,
    pub shape: u8,
    pub rotation: u8,
}

impl LocEntry {
    fn packed_pos(&self) -> i32 {
        ((self.level as i32) << 12) | ((self.x as i32) << 6) | (self.z as i32)
    }
}

// ── Binary → structured ───────────────────────────────────────────────────

pub fn parse_terrain_binary(data: &[u8]) -> TerrainData {
    parse_terrain_binary_levels(data, 4)
}

pub fn parse_terrain_binary_levels(data: &[u8], levels: usize) -> TerrainData {
    let tile_count = levels * 64 * 64;
    let mut tiles = Vec::with_capacity(tile_count);
    let mut pos = 0usize;

    for _ in 0..tile_count {
        let mut tile = TerrainTile::default();

        loop {
            if pos >= data.len() {
                break;
            }
            let opcode = data[pos] as u16;
            pos += 1;

            if opcode == 0 {
                break;
            } else if opcode == 1 {
                if pos < data.len() {
                    tile.height = Some(data[pos]);
                    pos += 1;
                }
                break;
            } else if opcode <= 49 {
                let packed = opcode - 2;
                tile.overlay_shape = (packed >> 2) as u8;
                tile.overlay_rotation = (packed & 3) as u8;
                if pos < data.len() {
                    tile.overlay_id = Some(data[pos]);
                    pos += 1;
                }
            } else if opcode <= 81 {
                tile.flags = Some((opcode - 49) as u8);
            } else {
                tile.underlay_id = Some((opcode - 81) as u8);
            }
        }

        tiles.push(tile);
    }

    // Parse environment metadata after the tile grid
    let mut env_opcode_order = Vec::new();
    let mut environment = None;
    let mut lights = Vec::new();
    let mut env_params = None;
    let mut skybox = None;
    let mut camera = None;

    while pos < data.len() {
        let opcode = data[pos];
        pos += 1;
        env_opcode_order.push(opcode);

        match opcode {
            0 => {
                environment = Some(parse_environment(data, &mut pos));
            }
            1 => {
                let count = read_u8(data, &mut pos);
                for _ in 0..count {
                    lights.push(parse_light(data, &mut pos));
                }
            }
            2 => {
                env_params = Some(EnvParams {
                    values: [
                        read_u8(data, &mut pos),
                        read_u8(data, &mut pos),
                        read_u8(data, &mut pos),
                    ],
                });
            }
            128 => {
                skybox = Some(SkyboxData {
                    param0: read_u16(data, &mut pos),
                    param1: read_i16(data, &mut pos),
                    param2: read_i16(data, &mut pos),
                    param3: read_i16(data, &mut pos),
                    param4: read_u16(data, &mut pos),
                });
            }
            129 => {
                let mut planes = [
                    CameraPlane::Clear,
                    CameraPlane::Clear,
                    CameraPlane::Clear,
                    CameraPlane::Clear,
                ];
                for plane in &mut planes {
                    let ptype = read_i8(data, &mut pos);
                    match ptype {
                        0 => *plane = CameraPlane::Clear,
                        1 => {
                            let mut cells = Vec::with_capacity(256);
                            for _ in 0..16 {
                                for _ in 0..16 {
                                    cells.push(read_i8(data, &mut pos));
                                }
                            }
                            *plane = CameraPlane::Data(cells);
                        }
                        2 => *plane = CameraPlane::CopyPrev,
                        _ => *plane = CameraPlane::Clear,
                    }
                }
                camera = Some(CameraData { planes });
            }
            _ => break,
        }
    }

    TerrainData {
        levels,
        tiles,
        env_opcode_order,
        environment,
        lights,
        env_params,
        skybox,
        camera,
    }
}

fn parse_environment(data: &[u8], pos: &mut usize) -> EnvironmentData {
    let flags = read_u8(data, pos);
    let sun_color = if flags & 0x01 != 0 {
        Some(read_u32(data, pos))
    } else {
        None
    };
    let ambient = if flags & 0x02 != 0 {
        Some(read_u16(data, pos))
    } else {
        None
    };
    let sunlight = if flags & 0x04 != 0 {
        Some(read_u16(data, pos))
    } else {
        None
    };
    let backlight = if flags & 0x08 != 0 {
        Some(read_u16(data, pos))
    } else {
        None
    };
    let sun_angle = if flags & 0x10 != 0 {
        Some([
            read_i16(data, pos),
            read_i16(data, pos),
            read_i16(data, pos),
        ])
    } else {
        None
    };
    let fog_color = if flags & 0x20 != 0 {
        Some(read_u32(data, pos))
    } else {
        None
    };
    let fog_depth = if flags & 0x40 != 0 {
        Some(read_u16(data, pos))
    } else {
        None
    };
    let env_map = if flags & 0x80 != 0 {
        Some([
            read_u16(data, pos),
            read_u16(data, pos),
            read_u16(data, pos),
            read_u16(data, pos),
            read_u16(data, pos),
            read_u16(data, pos),
        ])
    } else {
        None
    };
    EnvironmentData {
        sun_color,
        ambient,
        sunlight,
        backlight,
        sun_angle,
        fog_color,
        fog_depth,
        env_map,
    }
}

fn parse_light(data: &[u8], pos: &mut usize) -> LightData {
    let flags_raw = read_u8(data, pos);
    let x = read_u16(data, pos);
    let y = read_u16(data, pos);
    let z = read_u16(data, pos);
    let radius = read_u8(data, pos);
    let color_count = (radius as usize) * 2 + 1;
    let mut colors = Vec::with_capacity(color_count);
    for _ in 0..color_count {
        colors.push(read_u16(data, pos));
    }
    let hsl = read_u16(data, pos);
    let type_packed = read_u8(data, pos);
    let light_type = type_packed & 0x1F;
    let light_type_ref = if light_type == 31 {
        Some(read_u16(data, pos))
    } else {
        None
    };
    LightData {
        flags_raw,
        x,
        y,
        z,
        radius,
        colors,
        hsl,
        type_packed,
        light_type_ref,
    }
}

fn read_u8(data: &[u8], pos: &mut usize) -> u8 {
    let v = data.get(*pos).copied().unwrap_or(0);
    *pos += 1;
    v
}

fn read_i8(data: &[u8], pos: &mut usize) -> i8 {
    read_u8(data, pos) as i8
}

fn read_u16(data: &[u8], pos: &mut usize) -> u16 {
    let hi = data.get(*pos).copied().unwrap_or(0) as u16;
    let lo = data.get(*pos + 1).copied().unwrap_or(0) as u16;
    *pos += 2;
    (hi << 8) | lo
}

fn read_i16(data: &[u8], pos: &mut usize) -> i16 {
    read_u16(data, pos) as i16
}

fn read_u32(data: &[u8], pos: &mut usize) -> u32 {
    let a = data.get(*pos).copied().unwrap_or(0) as u32;
    let b = data.get(*pos + 1).copied().unwrap_or(0) as u32;
    let c = data.get(*pos + 2).copied().unwrap_or(0) as u32;
    let d = data.get(*pos + 3).copied().unwrap_or(0) as u32;
    *pos += 4;
    (a << 24) | (b << 16) | (c << 8) | d
}

pub fn parse_landscape_binary(data: &[u8]) -> Vec<LocEntry> {
    let mut locs = Vec::new();
    let mut cur = data;
    let mut loc_id: i32 = -1;

    loop {
        let delta = glargesmart(&mut cur);
        if delta == 0 {
            break;
        }
        loc_id += delta;

        let mut tile_pos: i32 = 0;
        loop {
            let offset = gsmart(&mut cur);
            if offset == 0 {
                break;
            }
            tile_pos += offset - 1;

            if cur.is_empty() {
                break;
            }
            let packed = cur[0];
            cur = &cur[1..];

            locs.push(LocEntry {
                loc_id: loc_id as u32,
                level: ((tile_pos >> 12) & 0x3) as u8,
                x: ((tile_pos >> 6) & 0x3f) as u8,
                z: (tile_pos & 0x3f) as u8,
                shape: packed >> 2,
                rotation: packed & 3,
            });
        }
    }

    locs
}

// ── Structured → binary ───────────────────────────────────────────────────

pub fn encode_terrain_binary(terrain: &TerrainData) -> Vec<u8> {
    let mut out = Vec::with_capacity(TILES_PER_MAP);

    for tile in &terrain.tiles {
        if let Some(id) = tile.overlay_id {
            let opcode = 2u8 + (tile.overlay_shape << 2) + tile.overlay_rotation;
            out.push(opcode);
            out.push(id);
        }

        if let Some(f) = tile.flags {
            out.push(f + 49);
        }

        if let Some(u) = tile.underlay_id {
            out.push(u + 81);
        }

        if let Some(h) = tile.height {
            out.push(1);
            out.push(h);
        } else {
            out.push(0);
        }
    }

    // Environment metadata — emit in the same order as the original binary
    for &opcode in &terrain.env_opcode_order {
        match opcode {
            0 => {
                if let Some(env) = &terrain.environment {
                    out.push(0);
                    encode_environment(env, &mut out);
                }
            }
            1 => {
                if !terrain.lights.is_empty() {
                    out.push(1);
                    out.push(terrain.lights.len() as u8);
                    for light in &terrain.lights {
                        encode_light(light, &mut out);
                    }
                }
            }
            2 => {
                if let Some(params) = &terrain.env_params {
                    out.push(2);
                    out.extend_from_slice(&params.values);
                }
            }
            128 => {
                if let Some(sky) = &terrain.skybox {
                    out.push(128);
                    write_u16(&mut out, sky.param0);
                    write_i16(&mut out, sky.param1);
                    write_i16(&mut out, sky.param2);
                    write_i16(&mut out, sky.param3);
                    write_u16(&mut out, sky.param4);
                }
            }
            129 => {
                if let Some(cam) = &terrain.camera {
                    out.push(129);
                    for plane in &cam.planes {
                        match plane {
                            CameraPlane::Clear => out.push(0),
                            CameraPlane::Data(cells) => {
                                out.push(1);
                                for &c in cells {
                                    out.push(c as u8);
                                }
                            }
                            CameraPlane::CopyPrev => out.push(2),
                        }
                    }
                }
            }
            _ => {}
        }
    }

    out
}

fn encode_environment(env: &EnvironmentData, out: &mut Vec<u8>) {
    let mut flags = 0u8;
    if env.sun_color.is_some() {
        flags |= 0x01;
    }
    if env.ambient.is_some() {
        flags |= 0x02;
    }
    if env.sunlight.is_some() {
        flags |= 0x04;
    }
    if env.backlight.is_some() {
        flags |= 0x08;
    }
    if env.sun_angle.is_some() {
        flags |= 0x10;
    }
    if env.fog_color.is_some() {
        flags |= 0x20;
    }
    if env.fog_depth.is_some() {
        flags |= 0x40;
    }
    if env.env_map.is_some() {
        flags |= 0x80;
    }
    out.push(flags);
    if let Some(v) = env.sun_color {
        write_u32(out, v);
    }
    if let Some(v) = env.ambient {
        write_u16(out, v);
    }
    if let Some(v) = env.sunlight {
        write_u16(out, v);
    }
    if let Some(v) = env.backlight {
        write_u16(out, v);
    }
    if let Some(a) = env.sun_angle {
        write_i16(out, a[0]);
        write_i16(out, a[1]);
        write_i16(out, a[2]);
    }
    if let Some(v) = env.fog_color {
        write_u32(out, v);
    }
    if let Some(v) = env.fog_depth {
        write_u16(out, v);
    }
    if let Some(m) = env.env_map {
        for v in m {
            write_u16(out, v);
        }
    }
}

fn encode_light(light: &LightData, out: &mut Vec<u8>) {
    out.push(light.flags_raw);
    write_u16(out, light.x);
    write_u16(out, light.y);
    write_u16(out, light.z);
    out.push(light.radius);
    for &c in &light.colors {
        write_u16(out, c);
    }
    write_u16(out, light.hsl);
    out.push(light.type_packed);
    if let Some(r) = light.light_type_ref {
        write_u16(out, r);
    }
}

fn write_u16(out: &mut Vec<u8>, v: u16) {
    out.push((v >> 8) as u8);
    out.push(v as u8);
}

fn write_i16(out: &mut Vec<u8>, v: i16) {
    write_u16(out, v as u16);
}

fn write_u32(out: &mut Vec<u8>, v: u32) {
    out.push((v >> 24) as u8);
    out.push((v >> 16) as u8);
    out.push((v >> 8) as u8);
    out.push(v as u8);
}

pub fn encode_landscape_binary(locs: &[LocEntry]) -> Vec<u8> {
    let mut sorted: Vec<&LocEntry> = locs.iter().collect();
    sorted.sort_by_key(|l| (l.loc_id, l.packed_pos()));

    let mut out = Vec::new();
    let mut last_id: i32 = -1;
    let mut i = 0;

    while i < sorted.len() {
        let id = sorted[i].loc_id as i32;
        write_lsmart(&mut out, id - last_id);
        last_id = id;

        let mut last_pos: i32 = 0;
        while i < sorted.len() && sorted[i].loc_id as i32 == id {
            let loc = sorted[i];
            let pos = loc.packed_pos();
            write_smart(&mut out, pos - last_pos + 1);
            last_pos = pos;
            out.push((loc.shape << 2) | loc.rotation);
            i += 1;
        }

        write_smart(&mut out, 0);
    }

    write_smart(&mut out, 0);
    out
}

// ── Structured → text ─────────────────────────────────────────────────────

pub fn emit_terrain_text(terrain: &TerrainData) -> String {
    let mut out = String::new();

    if terrain.levels != 4 {
        out.push_str(&format!("levels={}\n", terrain.levels));
    }

    for (index, tile) in terrain.tiles.iter().enumerate() {
        if !tile.has_any() {
            continue;
        }

        let level = index / (64 * 64);
        let x = (index / 64) % 64;
        let z = index % 64;

        out.push_str(&level.to_string());
        out.push(' ');
        out.push_str(&x.to_string());
        out.push(' ');
        out.push_str(&z.to_string());
        out.push(':');

        if let Some(h) = tile.height {
            out.push_str(" h");
            out.push_str(&h.to_string());
        }

        if let Some(id) = tile.overlay_id {
            out.push_str(" o");
            out.push_str(&id.to_string());
            if tile.overlay_shape != 0 || tile.overlay_rotation != 0 {
                out.push(';');
                out.push_str(&tile.overlay_shape.to_string());
                if tile.overlay_rotation != 0 {
                    out.push(';');
                    out.push_str(&tile.overlay_rotation.to_string());
                }
            }
        }

        if let Some(f) = tile.flags {
            out.push_str(" f");
            out.push_str(&f.to_string());
        }

        if let Some(u) = tile.underlay_id {
            out.push_str(" u");
            out.push_str(&u.to_string());
        }

        out.push('\n');
    }

    if !terrain.env_opcode_order.is_empty() {
        let order_str: Vec<String> = terrain
            .env_opcode_order
            .iter()
            .map(|o| o.to_string())
            .collect();
        out.push_str(&format!(
            "\n==== OPCODE_ORDER {} ====\n",
            order_str.join(",")
        ));
    }

    if let Some(env) = &terrain.environment {
        out.push_str("\n==== ENV ====\n");
        if let Some(v) = env.sun_color {
            out.push_str(&format!("sun_color={}\n", v));
        }
        if let Some(v) = env.ambient {
            out.push_str(&format!("ambient={}\n", v));
        }
        if let Some(v) = env.sunlight {
            out.push_str(&format!("sunlight={}\n", v));
        }
        if let Some(v) = env.backlight {
            out.push_str(&format!("backlight={}\n", v));
        }
        if let Some(a) = env.sun_angle {
            out.push_str(&format!("sun_angle={},{},{}\n", a[0], a[1], a[2]));
        }
        if let Some(v) = env.fog_color {
            out.push_str(&format!("fog_color={}\n", v));
        }
        if let Some(v) = env.fog_depth {
            out.push_str(&format!("fog_depth={}\n", v));
        }
        if let Some(m) = env.env_map {
            out.push_str(&format!(
                "env_map={},{},{},{},{},{}\n",
                m[0], m[1], m[2], m[3], m[4], m[5]
            ));
        }
    }

    if !terrain.lights.is_empty() {
        out.push_str("\n==== LIGHTS ====\n");
        for light in &terrain.lights {
            let colors_str: Vec<String> = light.colors.iter().map(|c| c.to_string()).collect();
            out.push_str(&format!(
                "{} {} {} {}: radius={} colors={} hsl={} type={}",
                light.flags_raw,
                light.x,
                light.y,
                light.z,
                light.radius,
                colors_str.join(","),
                light.hsl,
                light.type_packed
            ));
            if let Some(r) = light.light_type_ref {
                out.push_str(&format!(" ref={}", r));
            }
            out.push('\n');
        }
    }

    if let Some(params) = &terrain.env_params {
        out.push_str("\n==== ENVPARAMS ====\n");
        out.push_str(&format!(
            "{} {} {}\n",
            params.values[0], params.values[1], params.values[2]
        ));
    }

    if let Some(sky) = &terrain.skybox {
        out.push_str("\n==== SKYBOX ====\n");
        out.push_str(&format!(
            "{} {} {} {} {}\n",
            sky.param0, sky.param1, sky.param2, sky.param3, sky.param4
        ));
    }

    if let Some(cam) = &terrain.camera {
        out.push_str("\n==== CAMERA ====\n");
        for (i, plane) in cam.planes.iter().enumerate() {
            match plane {
                CameraPlane::Clear => out.push_str(&format!("{}: clear\n", i)),
                CameraPlane::Data(cells) => {
                    let vals: Vec<String> = cells.iter().map(|c| c.to_string()).collect();
                    out.push_str(&format!("{}: data {}\n", i, vals.join(",")));
                }
                CameraPlane::CopyPrev => out.push_str(&format!("{}: copy\n", i)),
            }
        }
    }

    out
}

